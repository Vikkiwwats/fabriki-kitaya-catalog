'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const source=fs.readFileSync(path.join(root,'docs/app.js'),'utf8');
const products=fs.readdirSync(path.join(root,'docs/data')).filter(p=>p.endsWith('.json')).flatMap(p=>JSON.parse(fs.readFileSync(path.join(root,'docs/data',p),'utf8')));
const medical='Протезы и бельё';
const nodes=new Map();
const node=selector=>{if(!nodes.has(selector))nodes.set(selector,{innerHTML:'',textContent:'',hidden:false,classList:{toggle(){}},value:''});return nodes.get(selector);};
function fn(name){const start=source.indexOf('  function '+name+'(');assert.notEqual(start,-1,name);const end=source.indexOf('\n  function ',start+4);assert.notEqual(end,-1,name);return source.slice(start,end);}
const state={products,map:new Map(products.map(p=>[p.id,p])),category:'',subcategory:'',query:'',idea:'',sort:'curated',limit:18,selection:[],medicalUnlocked:false,pendingMedical:null};
const context={state,DISCREET_CATEGORY:medical,HOLIDAY_CATEGORY:'Новый год',IDEAS:[],icon:()=>'',esc:v=>String(v??''),$:node,updateCounts(){}};
vm.createContext(context);
const labels=source.split('\n').filter(l=>l.startsWith('  const plural=')||l.startsWith('  const productsWord=')).join('\n');
vm.runInContext(labels+'\n'+['curated','filtered','orderedCategories','relatedProducts','atlasGrid','productImg','productCard','renderFilters','render','buildDiscovery'].map(fn).join('\n'),context);
const publicCount=products.filter(p=>p.category!==medical).length;
assert.equal(context.filtered().length,publicCount);
assert(context.filtered().every(p=>p.category!==medical));
state.query='FK-P017';assert.equal(context.filtered().length,0,'Global search must not reveal the separate category');state.query='';
context.render();assert(!node('#products-grid').innerHTML.includes('FK-P'));
context.buildDiscovery();
for(const p of products.filter(p=>p.category===medical))assert(!node('#direction-grid').innerHTML.includes(p.image),'Discovery cannot contain a medical photo');
assert(node('#direction-grid').innerHTML.endsWith('Открыть <span aria-hidden="true">↗</span></span></button>'));
assert.equal(context.orderedCategories().at(-1),medical);
assert.equal(context.orderedCategories()[0],'Новый год');
state.category=medical;context.render();
assert.equal(context.filtered().length,0);assert.equal(node('#products-grid').innerHTML,'');assert.equal(node('#protected-category').hidden,false);
const p=products.find(p=>p.category===medical);
assert(!context.productImg(p).includes(p.image));assert.equal(context.relatedProducts(p).length,0);
state.medicalUnlocked=true;context.render();
assert.equal(context.filtered().length,products.filter(p=>p.category===medical).length);assert.equal(node('#protected-category').hidden,true);
assert(context.productImg(p).includes(p.image));
state.category='Новый год';context.render();
assert.equal(state.medicalUnlocked,false,'Leaving the separate category restores the cover');
assert.equal(node('#holiday-feature').hidden,false);assert.equal(node('#holiday-navigation').hidden,false);
assert.equal(context.filtered().length,products.filter(p=>p.category==='Новый год').length);
state.category='Кухня';context.render();assert.equal(node('#holiday-feature').hidden,true);
for(const product of products.filter(p=>p.category!==medical))assert(context.relatedProducts(product).every(p=>p.category===product.category&&p.category!==medical));
assert.equal(context.atlasGrid('assets/products/newyear-photos-001.webp').cols,4);
assert.equal(context.atlasGrid('assets/products/newyear-photos-006.webp').rows,4);
console.log('Passed visibility, deliberate reveal, category ordering, recommendations, theme and photo-grid checks.');
